import {test,expect} from '@playwright/test';
test('v1 finances layout, expandable reports and transaction editing work on mobile',async({page})=>{
  await page.goto('/#finances');
  const headers=page.locator('.fin-section-header');
  await expect(headers).toHaveText(['schoolWynagrodzenia instruktorówexpand_less','analyticsZysk i stratyexpand_more','receipt_longTransakcjeexpand_more','tuneUstawienia stawekexpand_more']);
  await expect(page.getByRole('switch',{name:'Ania',exact:true})).toBeEnabled();
  const today=new Intl.DateTimeFormat('sv-SE',{timeZone:'Europe/Warsaw'}).format(new Date());
  const prior=new Date(today+'T12:00:00Z');prior.setUTCDate(prior.getUTCDate()-7);
  await expect(page.getByLabel('Od',{exact:true})).toHaveValue(prior.toISOString().slice(0,10));
  await expect(page.getByLabel('do',{exact:true})).toHaveValue(today);
  await page.screenshot({path:'test-results/finances-v1-mobile.png',fullPage:true});
  await page.getByRole('button',{name:/Ania.*zł/}).click();
  await page.getByRole('button',{name:'Raport szczegółowy',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('Ania');
  await page.getByRole('button',{name:'Zamknij',exact:true}).click();
  await page.getByRole('button',{name:'Zysk i straty',exact:true}).click();
  await expect(page.getByText('Zysk netto',{exact:true})).toBeVisible();
  await page.getByRole('switch',{name:'Ania',exact:true}).click();
  await expect(page.getByRole('switch',{name:'Ania',exact:true})).toHaveAttribute('aria-checked','false');
  await page.getByRole('button',{name:'Transakcje',exact:true}).click();
  await page.getByRole('button',{name:'Dodaj transakcję',exact:true}).click();
  const editor=page.getByRole('dialog',{name:'Dodaj transakcję'});
  await editor.getByRole('button',{name:'Przychód',exact:true}).click();
  await editor.getByLabel('Tytuł').fill('Wpłata UI');await editor.getByLabel('Wartość').fill('123.45');
  await page.screenshot({path:'test-results/finances-v1-editor-mobile.png',fullPage:true});
  await editor.getByRole('button',{name:'Dodaj',exact:true}).click();
  await expect(editor).toHaveCount(0);
  await expect(page.locator('.fin-exp-row').filter({hasText:'Wpłata UI'})).toContainText('+123.45 zł');
  await page.locator('.fin-exp-row').filter({hasText:'Wpłata UI'}).click();
  const edit=page.getByRole('dialog',{name:'Edytuj transakcję'});await edit.getByLabel('Wartość').fill('124');await edit.getByRole('button',{name:'Zapisz',exact:true}).click();
  await expect(page.locator('.fin-exp-row').filter({hasText:'Wpłata UI'})).toContainText('+124 zł');
  await page.getByRole('button',{name:'Ustawienia stawek',exact:true}).click();
  await expect(page.locator('.fin-section').last().locator('input[type=number]')).toHaveCount(4);
  await page.getByLabel('Jazda indywidualna w karnecie (zł/h)',{exact:true}).fill('65');
  await page.getByRole('button',{name:'Zapisz stawki raportów'}).click();
  await expect(page.getByRole('button',{name:'Zapisz stawki raportów'})).toHaveCount(0);
  await page.reload();
  await page.getByRole('button',{name:'Ustawienia stawek',exact:true}).click();
  await expect(page.getByLabel('Jazda indywidualna w karnecie (zł/h)',{exact:true})).toHaveValue('65');
  await page.setViewportSize({width:1280,height:900});
  await page.screenshot({path:'test-results/finances-v1-desktop.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
